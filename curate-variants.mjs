import fs from 'node:fs';
import {
  variantPuzzle,
  variantModes,
  variantCatalog,
  variantPlan,
  variantAct,
  variantStatus,
} from './lib/variants.mjs';
import { variantDifficulty, variantTiers } from './lib/variant-difficulty.mjs';
import { variantFingerprint } from './lib/variant-fingerprint.mjs';
import { fresh } from './lib/session.mjs';

const specs = [],
  report = [];
for (const mode of variantModes) {
  const buckets = Object.fromEntries(variantTiers.map((t) => [t, []])),
    seen = new Set();
  // Keep every previously published puzzle and its stable ID, even if reclassified.
  for (const l of variantCatalog)
    if (l.mode === mode && l.id.startsWith('variant-v1-')) {
      const d = variantDifficulty(l);
      buckets[d.tier].push({ l, d });
      seen.add(variantFingerprint(l));
    }
  for (
    let seed = 100000;
    seed < 120000 && variantTiers.some((t) => buckets[t].length < 80);
    seed++
  ) {
    const n = [3, 4, 5, 6][seed % 4],
      id = `variant-v2-${mode}-catalog-${n}-${seed}`;
    const l = variantPuzzle(mode, seed, n, id, 2),
      d = variantDifficulty(l),
      key = variantFingerprint(l);
    if (seen.has(key) || buckets[d.tier].length >= 80) continue;
    // Avoid nearly solved starts; this is not used as the difficulty score.
    if (variantPlan(l, fresh(l)).length < 4) continue;
    seen.add(key);
    buckets[d.tier].push({ l, d });
  }
  for (const tier of variantTiers) {
    const legacy = buckets[tier].filter((x) =>
      x.l.id.startsWith('variant-v1-'),
    );
    const remaining = buckets[tier]
      .filter((x) => !x.l.id.startsWith('variant-v1-'))
      .sort((a, b) => a.d.score - b.d.score);
    const selected = [...legacy];
    // Sample the whole band rather than taking only its easiest candidates.
    const needed = 30 - selected.length;
    if (remaining.length < needed) throw Error(`Not enough ${mode}/${tier}`);
    for (let i = 0; i < needed; i++)
      selected.push(remaining[Math.floor((i * remaining.length) / needed)]);
    selected.sort(
      (a, b) => a.d.score - b.d.score || a.l.id.localeCompare(b.l.id),
    );
    for (const { l, d } of selected) {
      let s = fresh(l);
      for (const action of variantPlan(l, s)) s = variantAct(l, s, action);
      if (!variantStatus(l, s).solved) throw Error(l.id);
      specs.push({
        mode,
        n: l.n,
        seed: l.seed,
        id: l.id,
        generation: l.generatorVersion || 1,
        difficulty: d,
      });
    }
    report.push({
      mode,
      tier,
      count: selected.length,
      min: selected[0].d.score,
      max: selected.at(-1).d.score,
      sizes: [...new Set(selected.map((x) => x.l.n))].sort().join(','),
    });
  }
}
fs.writeFileSync(
  'lib/variant-catalog-data.mjs',
  '// Published puzzle identities are permanent. Generated by curate-variants.mjs.\nexport const variantCatalogSpecs = ' +
    JSON.stringify(specs, null, 2) +
    ';\n',
);
console.table(report);
